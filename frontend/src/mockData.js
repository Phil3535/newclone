export const getTrending = () => {
  return getAllContent().sort(() => Math.random() - 0.5).slice(0, 10);
};

export const getByGenre = (genre) => {
  return getAllContent().filter(item => item.genre.includes(genre));
};

export const searchContent = (query) => {
  const lowerQuery = query.toLowerCase();
  return getAllContent().filter(item => 
    item.title.toLowerCase().includes(lowerQuery) ||
    item.genre.toLowerCase().includes(lowerQuery) ||
    item.synopsis.toLowerCase().includes(lowerQuery)
  );
};